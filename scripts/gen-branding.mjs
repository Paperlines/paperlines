// Generates every file that embeds brand strings from branding/branding.json.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const b = JSON.parse(readFileSync(resolve(root, "branding/branding.json"), "utf8"));
const out = (rel, text) => {
  const p = resolve(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, text);
};
const q = JSON.stringify;
const slug = b.dataFolder.toLowerCase();

out(
  "crates/core/src/branding.generated.rs",
  `// @generated by scripts/gen-branding.mjs from branding/branding.json. Do not edit.
pub const DISPLAY_NAME: &str = ${q(b.displayName)};
pub const BINARY_NAME: &str = ${q(b.binaryName)};
pub const CLI_COMMAND: &str = ${q(b.cliCommand)};
pub const APP_ID: &str = ${q(b.appId)};
pub const DATA_FOLDER: &str = ${q(b.dataFolder)};
pub const DESCRIPTION: &str = ${q(b.description)};
`,
);

out(
  "src/branding.generated.ts",
  `// @generated by scripts/gen-branding.mjs from branding/branding.json. Do not edit.
export const branding = ${JSON.stringify(
    {
      displayName: b.displayName,
      // the start of the name set in bold in the top bar (the rest regular), as in the logo
      wordmarkBold: b.displayName.startsWith(b.wordmarkBold ?? "") ? (b.wordmarkBold ?? "") : "",
      cliCommand: b.cliCommand,
      appId: b.appId,
      description: b.description,
      version: b.version,
      summary: b.summary ?? "",
      // project links: empty until published; Help & About shows a row only for those set
      repository: b.repository ?? "",
      website: b.website ?? "",
      license: b.license ?? "",
      author: b.author ?? "",
    },
    null,
    2,
  )} as const;
`,
);

const conf = {
  $schema: "https://schema.tauri.app/config/2",
  productName: b.displayName,
  version: b.version,
  identifier: b.appId,
  build: {
    beforeDevCommand: "node scripts/build-cli.mjs --debug && pnpm dev",
    devUrl: "http://localhost:1420",
    beforeBuildCommand: "pnpm build && node scripts/build-cli.mjs",
    frontendDist: "../dist",
  },
  app: {
    // Linux: register the GTK application ID (= identifier) so Wayland desktops (COSMIC, GNOME,
    // KDE) match the window to its .desktop entry: right icon and name, grouped in the dock.
    // It also makes GTK enforce one instance, which the single-instance plugin does anyway.
    enableGTKAppId: true,
    // macOS: content under an overlay title bar (traffic lights inset); other systems keep native frames
    windows: [
      {
        title: b.displayName,
        width: 1360,
        height: 860,
        minWidth: 960,
        minHeight: 600,
        titleBarStyle: "Overlay",
        hiddenTitle: true,
        trafficLightPosition: { x: 16, y: 21 },
      },
    ],
    security: {
      csp: "default-src 'self'; img-src 'self' data: blob:; style-src 'self' 'unsafe-inline'; connect-src 'self' ipc: http://ipc.localhost",
    },
  },
  bundle: {
    active: true,
    // macOS: .app + .dmg; Linux: .deb, .rpm, AppImage; Windows: setup .exe (NSIS) + .msi
    targets: "all",
    category: "Productivity",
    shortDescription: b.description,
    icon: [
      "icons/32x32.png",
      "icons/128x128.png",
      "icons/128x128@2x.png",
      "icons/icon.icns",
      "icons/icon.ico",
    ],
    // the command-line tool ships inside the bundle (macOS: Contents/MacOS, deb/rpm: /usr/bin)
    externalBin: [`binaries/${b.binaryName}`],
    macOS: {
      minimumSystemVersion: "12.0",
      // required for notarization; signing itself comes from APPLE_* environment variables
      hardenedRuntime: true,
      signingIdentity: null,
      // the classic drag-to-Applications window
      dmg: {
        windowSize: { width: 660, height: 400 },
        appPosition: { x: 180, y: 190 },
        applicationFolderPosition: { x: 480, y: 190 },
      },
    },
    linux: {
      deb: { section: "science", desktopTemplate: "../branding/linux.desktop.hbs" },
      rpm: { desktopTemplate: "../branding/linux.desktop.hbs" },
      appimage: { bundleMediaFramework: false },
    },
    // Windows: a per-user install (no admin); WebView2 is fetched by the installer if missing
    windows: {
      webviewInstallMode: { type: "downloadBootstrapper" },
      nsis: { installMode: "currentUser", displayLanguageSelector: false },
      wix: { language: "en-US" },
    },
    // "can open" only: Alternate rank never makes the app the default for these types
    fileAssociations: [
      {
        ext: ["pdf"],
        name: "PDF document",
        mimeType: "application/pdf",
        role: "Viewer",
        rank: "Alternate",
      },
      {
        ext: ["bib"],
        name: "BibTeX file",
        mimeType: "application/x-bibtex",
        role: "Viewer",
        rank: "Alternate",
      },
      {
        ext: ["ris"],
        name: "RIS file",
        mimeType: "application/x-research-info-systems",
        role: "Viewer",
        rank: "Alternate",
      },
    ],
  },
  // In-app updates: the release workflow publishes signed bundles and latest.json on GitHub
  // Releases (it also turns on bundle.createUpdaterArtifacts, so local builds need no key).
  plugins: {
    updater: {
      pubkey: b.updaterPubkey ?? "",
      endpoints: b.repository
        ? [`${b.repository.replace(/\/$/, "")}/releases/latest/download/latest.json`]
        : [],
      windows: { installMode: "passive" },
    },
  },
};
out("src-tauri/tauri.conf.json", JSON.stringify(conf, null, 2) + "\n");

// Linux .desktop entry (deb/rpm template; the Nix package installs it as <identifier>.desktop).
// StartupWMClass is the Wayland app ID, which enableGTKAppId sets to the identifier.
const mime = conf.bundle.fileAssociations.map((a) => a.mimeType).join(";");
out(
  "branding/linux.desktop.hbs",
  `[Desktop Entry]
Type=Application
Name={{name}}
GenericName=Reference Manager
Comment={{comment}}
Exec={{exec}} %U
Icon={{icon}}
StartupWMClass=${b.appId}
Terminal=false
Categories=Office;Education;Science;
Keywords=references;citations;bibliography;bibtex;papers;pdf;zotero;
MimeType=${mime};
`,
);
console.log(`branding generated for ${b.displayName} (${slug})`);
